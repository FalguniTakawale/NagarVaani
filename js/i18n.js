let lang = 'en';
try { lang = localStorage.getItem('nv_lang') || 'en'; } catch (_) {}
if (!TRANSLATIONS[lang]) lang = 'en';

export function currentLang() { return lang; }

export function t(key, vars = {}) {
  const s = (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) || TRANSLATIONS.en[key] || key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`));
}

/* Walks the DOM: data-i18n → textContent, data-i18n-placeholder → placeholder,
   data-i18n-title → title. Elements keep any child markup only if the key is
   put on a leaf span, which is how the HTML is annotated. */
export function applyLanguage(next) {
  if (next && TRANSLATIONS[next]) {
    lang = next;
    try { localStorage.setItem('nv_lang', lang); } catch (_) {}
  }
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  document.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
  document.querySelectorAll('[data-lang]').forEach(el => el.classList.toggle('selected', el.dataset.lang === lang));
  const btn = document.getElementById('topbar-lang-btn');
  if (btn) btn.textContent = lang.toUpperCase() + ' ▾';
}

export function setLanguage(next) {
  applyLanguage(next);
  const menu = document.getElementById('lang-menu');
  if (menu) menu.hidden = true;
}

export function toggleLangMenu(event) {
  if (event) event.stopPropagation();
  const menu = document.getElementById('lang-menu');
  menu.hidden = !menu.hidden;
  if (!menu.hidden) {
    const close = (e) => { if (!menu.contains(e.target)) { menu.hidden = true; document.removeEventListener('click', close); } };
    setTimeout(() => document.addEventListener('click', close), 0);
  }
}
